#!/usr/bin/env python3
"""Materialise the merged Roblox tree the library's test project needs.

WHY THIS EXISTS
---------------
Every library source file keeps its EXACT original Roblox path inside
`Systems/<Sys>/Source/`, so absolute requires such as
`require(ServerScriptService.AnimalService)` resolve unchanged.

The specs, however, live in PER-SYSTEM folders (`Systems/<Sys>/Tests/`) for
browsability, while they were written against the source game's FLAT test
layout -- every spec sat next to `_Helpers.lua` and reached it with
`require(script.Parent._Helpers)`.

Rojo cannot merge two filesystem folders into one instance, and the library
spreads one Roblox path across many systems (e.g.
`ReplicatedStorage/Config/World` is contributed by six systems). So the
merged tree has to exist on disk.

It is built from HARD LINKS (symlinks where the platform allows them):
every file in the merged tree is a link to the one real copy inside its
owning system folder. Nothing is copied, so "one physical home per file"
still holds and the tree costs no extra disk space.

The output lives in `ReusableSystems/Tests/Tree/` and is a BUILD ARTEFACT
-- it is regenerated by this script and must not be edited by hand.

Usage:
    python ReusableSystems/Tools/generate_test_tree.py
"""

import errno
import os
import re
import shutil
import sys

COPIED = []

HERE = os.path.dirname(os.path.abspath(__file__))
LIB = os.path.abspath(os.path.join(HERE, ".."))
OUT = os.path.join(LIB, "Tests", "Tree")


def roblox_path_of(rel, sysname):
    """Library-relative path -> the Roblox path it must live at."""
    m = re.match(r"^Systems/[^/]+/Source/(.*)$", rel)
    if m:
        return m.group(1)
    if rel.startswith("Shared/Types/"):
        return "ReplicatedStorage/Types/" + rel[len("Shared/Types/"):]
    if rel.startswith("Shared/Utilities/"):
        return "ReplicatedStorage/Utility/" + rel[len("Shared/Utilities/"):]
    if rel.startswith("Shared/CommonModules/"):
        fn = rel[len("Shared/CommonModules/"):]
        if fn == "ShopAnimations.lua":
            return "ReplicatedStorage/ShopAnimations.lua"
        return "ReplicatedStorage/Utility/" + fn
    return None


def link(dest, src):
    """Link dest -> src, preferring a hard link (works unprivileged).

    Falls back to a symlink, then to a copy. A copy is a last resort and
    means the tree is NOT live; the script says so when it happens.
    """
    try:
        os.link(src, dest)
        return
    except OSError as exc:
        if exc.errno not in (errno.EXDEV, errno.EPERM, errno.EACCES, errno.ENOSYS):
            raise
    try:
        os.symlink(os.path.relpath(src, os.path.dirname(dest)), dest)
        return
    except OSError:
        pass
    shutil.copy2(src, dest)
    COPIED.append(dest)


def collect():
    """Yield (roblox_path, absolute_source_path) for every library file."""
    out = []
    for root, _d, files in os.walk(LIB):
        if os.sep + "Tree" + os.sep in root or root.endswith(os.sep + "Tree"):
            continue
        for fn in files:
            if not fn.endswith((".lua", ".luau")):
                continue
            full = os.path.join(root, fn)
            rel = os.path.relpath(full, LIB).replace(os.sep, "/")
            if rel.startswith(("Examples/", "Tools/")):
                continue
            if "/Tests/" in "/" + rel or rel.startswith("Tests/"):
                continue
            rp = roblox_path_of(rel, None)
            if rp is None:
                continue
            out.append((rp, full))
    return out


def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT)

    entries = collect()
    # Group by target directory so each directory is created once.
    made = set()
    for rp, src in sorted(entries):
        dest = os.path.join(OUT, rp.replace("/", os.sep))
        d = os.path.dirname(dest)
        if d not in made:
            os.makedirs(d, exist_ok=True)
            made.add(d)
        if os.path.lexists(dest):
            # A duplicate Roblox path would mean two systems own one file.
            raise SystemExit(
                "DUPLICATE Roblox path: %s\n  %s\n  %s" % (rp, src, dest)
            )
        link(dest, src)

    print("materialised merged tree: %s" % os.path.relpath(OUT, LIB))
    print("  files linked : %d" % len(entries))
    print("  directories  : %d" % len(made))

    # The flat spec folder: every spec + _Helpers as siblings, exactly the
    # source game's TestEZTests layout, so `require(script.Parent._Helpers)`
    # resolves.
    spec_dir = os.path.join(OUT, "ServerScriptService", "TestEZTests")
    os.makedirs(spec_dir, exist_ok=True)
    n_spec = 0
    for root, _d, files in os.walk(LIB):
        if os.sep + "Tree" + os.sep in root or root.endswith(os.sep + "Tree"):
            continue
        for fn in files:
            if not fn.endswith(".spec.lua"):
                continue
            full = os.path.join(root, fn)
            rel = os.path.relpath(full, LIB).replace(os.sep, "/")
            if rel.startswith("Examples/"):
                continue
            dest = os.path.join(spec_dir, fn)
            if os.path.lexists(dest):
                raise SystemExit("duplicate spec name: %s" % fn)
            link(dest, full)
            n_spec += 1

    # _Helpers must be a sibling of the specs.
    helpers = os.path.join(LIB, "Tests", "_Helpers.lua")
    dest = os.path.join(spec_dir, "_Helpers.lua")
    link(dest, helpers)

    print("  specs linked : %d (+ _Helpers.lua)" % n_spec)
    if COPIED:
        print()
        print("WARNING: %d file(s) had to be COPIED (no link support)." % len(COPIED))
        print("         The tree is a snapshot, not live. Re-run this script")
        print("         after editing a system file.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
