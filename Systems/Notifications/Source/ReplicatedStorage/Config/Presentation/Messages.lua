--[[
	SuccessMessages
	===============
	Companion to WarningMessages.lua: the pure-data catalog for
	SUCCESS notifications (player action committed server-side).
	Same shape and conventions: stable Ids, short satisfying
	wording, {Placeholder} templates resolved server-side with
	authoritative data (NotificationService formats; the client
	never calculates).

	Entries exist ONLY for actions that really commit:
	  Buy / Pickup / Hatch / Place / Steal start / Steal delivery /
	  Upgrade / Sell (animals only — eggs are not sellable) /
	  Base lock / Gear / Arena.

	Sound policy (pure data; the service interprets):
	  'Approved' — Assets.Sfx.Approved sting (meaningful commits:
	             buy-at-arrival, steal delivery, lock).
	  'CashClaim' — Assets.Sfx.CashClaim (sale payout only).
	  'None'   — visual only. High-frequency movement actions
	             (pickup/place), hatch (the roulette already
	             played Reward at reveal), ambient arrivals,
	             steal start, and upgrades (LevelUp SFX covers
	             real level increases) stay quiet so audio never
	             stacks.
]]

