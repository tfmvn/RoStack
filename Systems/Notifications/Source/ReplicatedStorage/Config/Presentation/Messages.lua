--[[
	WarningMessages
	===============
	Player-facing rejection/warning catalog. Every entry traces to a
	real code path (Source + Code); NotificationService resolves
	Message templates with {Placeholders} at runtime. Silent/Internal
	severities never reach the player.

	Severity:
	  "Warning"  — the player explicitly attempted an action and
	               needs feedback. Shows a notification.
	  "Silent"   — normal race / debounce / internal state where a
	               warning would annoy. Shows nothing.
	  "Internal" — developer / system failure. Logs only.

	Dynamic messages carry NeedsData (variable names only — no
	formatting implemented here).

	Conventions: Ids are stable (<System>_<Case>). Messages are
	short, actionable, player-friendly, free of developer
	terminology. Prompt tuning is canonical in PromptConfig — the
	matrix below mirrors it (verified in code):
	  Buy prompt      — center egg, "Buy $X", E hold 0.4, 12 studs,
	                    UNNAMED instance (CarryPrompts-agnostic)
	  PickupPrompt    — "Pick up", E hold 1, owner-only, 8 studs
	  HatchPrompt     — "Hatch", F instant, owner-only, 8 studs
	  StealPrompt     — "Steal", E instant, non-owner-only, 8 studs
	  SellPrompt      — "Sell", F instant, owner-only, 8 studs
	  PlacePrompt     — "Place", E hold 1, targetUserId-stamped, 8 studs
	  Arena prompt    — "Open Arena", E instant, 12 studs
	  Gear prompt     — "Open Gear Shop", E instant, 12 studs
	  LazerButton     — Touched (base lock)
	  Collectors      — Touched (cash collect + steal delivery)
	  Legacy InstallGrabPrompt shim — DEAD, zero callers, no entries.

	Historical note: this catalog began as a Phase 1 audit-only list
	("rebirth / arena / trading do not exist"). Arena + Gear systems
	now exist and carry entries below; Gear 'Requires Rebirth' text
	survives as a locked-state label (no rebirth system yet).
]]

export type WarningEntry = {
